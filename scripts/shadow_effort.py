"""Shadow record of actual agentic-coding effort, derived from git and implementation-log.md.

A measured lower bound for learning only. It is NOT a schedule input: schedules stay in
human-engineering person-days (Sponsor, 2026-11-10). It excludes human review and thinking time
that leaves no commit, and it counts no tokens. Generated; never hand-edited.
"""
from __future__ import annotations

import re
import subprocess
import sys
from collections import defaultdict
from datetime import datetime, timedelta
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
GAP = timedelta(hours=2)
PHASE2_EPICS = {"14": "baseline", "16": "baseline", "18": "baseline", "21": "baseline", "22": "baseline", "38": "baseline", "17": "not in PMP-BL-v1.1.0"}


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=REPO, capture_output=True, text=True, encoding="utf8", check=True).stdout


def logged_stories() -> dict[str, int]:
    log = (REPO / "implementation-log.md").read_text(encoding="utf8")
    out: dict[str, int] = defaultdict(int)
    for m in re.finditer(r"^## Story (\d+)\.\d+", log, re.M):
        out[m.group(1)] += 1
    return out


def story_commits() -> dict[str, tuple[str, datetime]]:
    log = (REPO / "implementation-log.md").read_text(encoding="utf8")
    out: dict[str, tuple[str, datetime]] = {}
    for m in re.finditer(r"^## Story (\d+\.\d+)\b.*?\n- \*\*Commit:\*\* `([0-9a-f]{7,40})`", log, re.M | re.S):
        story, sha = m.group(1), m.group(2)
        r = subprocess.run(["git", "show", "-s", "--format=%aI", sha], cwd=REPO, capture_output=True, text=True, encoding="utf8")
        if r.returncode == 0 and r.stdout.strip():
            out.setdefault(story, (sha, datetime.fromisoformat(r.stdout.strip())))
    return out


def sessions(times: list[datetime]) -> list[tuple[datetime, datetime]]:
    times = sorted(times)
    if not times:
        return []
    out, start, prev = [], times[0], times[0]
    for t in times[1:]:
        if t - prev > GAP:
            out.append((start, prev))
            start = t
        prev = t
    out.append((start, prev))
    return out


def hours(td: timedelta) -> float:
    return round(td.total_seconds() / 3600, 1)


def main(since: str) -> str:
    stories = story_commits()
    logged = logged_stories()
    by_epic: dict[str, list[datetime]] = defaultdict(list)
    for s, (_, t) in stories.items():
        by_epic[s.split(".")[0]].append(t)
    all_commits = [datetime.fromisoformat(l) for l in git("log", "--no-merges", f"--since={since}", "--format=%aI").split() if l]
    sess = sessions(all_commits)
    total = sum((b - a for a, b in sess), timedelta())
    lines = [
        f"# Shadow Record of Agentic Coding Effort (generated {datetime.now().date()})",
        "",
        "Generated by `scripts/shadow_effort.py` from git author times and `implementation-log.md`; never edited by hand.",
        "",
        "> **Learning only. Not a schedule input.** Schedules stay in human-engineering person-days (Sponsor, 2026-11-10). "
        "These are measured lower bounds: they exclude human review and thinking time that leaves no commit, and they count no tokens or agent-hours.",
        "",
        f"## Phase 2 working sessions since {since}",
        "",
        f"Commits are grouped into a session while the gap between neighbours is at most {int(GAP.total_seconds() // 3600)} h; a session's length is last commit minus first.",
        "",
        "| Measure | Value |",
        "|---|---|",
        f"| Non-merge commits | {len(all_commits)} |",
        f"| Sessions | {len(sess)} |",
        f"| Calendar days with commits | {len({t.date() for t in all_commits})} |",
        f"| Session time (lower bound) | {hours(total)} h |",
        "",
        "## Logged stories by epic",
        "",
        "| Epic (scope) | Logged stories | With a resolvable commit | First commit | Last commit | Calendar days | Window |",
        "|---|---|---|---|---|---|---|",
    ]
    for e in sorted((e for e in by_epic if e in PHASE2_EPICS), key=int):
        ts = sorted(by_epic[e])
        lines.append(f"| {e} ({PHASE2_EPICS[e]}) | {logged[e]} | {len(ts)} | {ts[0]:%Y-%m-%d %H:%M} | {ts[-1]:%Y-%m-%d %H:%M} | {len({t.date() for t in ts})} | {hours(ts[-1] - ts[0])} h |")
    lines += [
        "",
        "Only Phase 2 epics are listed. A window is first to last story commit and includes idle time between them; it is not effort. Windows overlap because epics were worked in parallel, so they do not add up to the session total above. "
        "Stories whose logged commit hash no longer resolves in git (for example after a rebase) are logged but not timed, so the timed set is a subset and the figures are lower bounds.",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    since = sys.argv[1] if len(sys.argv) > 1 else "2026-11-01"
    out = REPO / "docs" / "project-docs" / "Status-Reports" / "Shadow-Agentic-Effort-Phase-2.md"
    out.write_text(main(since), encoding="utf8")
    print(out)
